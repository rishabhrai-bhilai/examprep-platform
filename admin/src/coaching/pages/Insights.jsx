// 17. AI-powered performance insights (rule-based for now; see the MODEL HOOK in
// server/coaching/analytics.js for where a model call plugs in)
import { useState } from 'react'
import { Sparkles } from 'lucide-react'
import { useCoaching, useWorkspace } from '../api'
import { Load, Panel, PageTitle, BatchSelect, InsightList, AutomatedLabel, ExportButtons } from '../kit'
import { downloadXlsx } from '../reports'

const KINDS = [['', 'All'], ['risk', 'Risk'], ['engagement', 'Engagement'], ['weakness', 'Weak topics'], ['test', 'Tests'], ['task', 'To do'], ['strength', 'Good news']]

export default function Insights() {
  const { batchId, info } = useWorkspace()
  const [kind, setKind] = useState('')
  const state = useCoaching('/insights', { batchId })
  return (
    <div className="space-y-6">
      <PageTitle title="Automated insights" subtitle="What the numbers say, written out, with a suggested action for each"
        right={<><BatchSelect />{state.data && <ExportButtons onXlsx={() => downloadXlsx([{ name: 'Insights', rows: [['Severity', 'Type', 'Insight', 'Detail', 'Suggested action'], ...state.data.items.map(i => [i.severity, i.kind, i.title, i.detail, i.action || ''])] }], `${info.centre.name}-insights`)} />}</>} />
      <div className="p-3 rounded-2xl bg-primary/5 border border-primary/20 text-[11px] text-slate-600 dark:text-slate-300 flex gap-2">
        <Sparkles size={14} className="text-primary shrink-0 mt-0.5" />
        <span>These are <b>automated insights</b> generated by rules from test results, practice answers, attendance-style activity, assignments and the course log. No AI model is called yet; the API already returns them in the shape a model would, so one can be plugged in later without changing this page.</span>
      </div>
      <Load state={state}>{(d) => {
        const items = d.items.filter(i => !kind || i.kind === kind)
        return (
          <Panel title={`${d.items.length} insights`} right={<AutomatedLabel />}>
            <div className="flex flex-wrap gap-1.5 mb-4">
              {KINDS.map(([k, label]) => <button key={k} onClick={() => setKind(k)} className={`px-2.5 py-1 rounded-full text-[11px] font-bold border ${kind === k ? 'border-primary bg-primary/10 text-primary' : 'border-border-light dark:border-border-dark text-slate-500'}`}>{label} ({k ? d.items.filter(i => i.kind === k).length : d.items.length})</button>)}
            </div>
            <InsightList items={items} />
          </Panel>
        )
      }}</Load>
    </div>
  )
}
