// Builds the PYQ sectional (subject-wise) mocks from past-paper questions so each
// paper covers the subject's chapters in proportion to shared/syllabusChapters.js.
// Run from the repo root: node scripts/generate-pyq-sectionals.mjs
// It rewrites the block between the PYQ-SECTIONALS markers in shared/mockTests.js.
// Uses a fixed seed, so the same question bank always gives the same papers.
import fs from 'fs'
import { SYLLABUS_CHAPTERS, chapterQuotas } from '../shared/syllabusChapters.js'
import { mockTests } from '../shared/mockTests.js'

const ROUNDS = 2
const PER_PAPER = 15
const ONE_MARK = 7 // and 8 two-mark questions, as in the other sectionals

const questions = JSON.parse(fs.readFileSync('src/data/questions.json', 'utf8'))
const usable = questions.filter(q => !q.marksToAll && q.answer !== null && q.answer !== undefined && q.answer !== '')

// Questions in the full-length and quick mocks stay out of the sectionals
const taken = new Set(mockTests.filter(t => !t.id.startsWith('pyq-sectional-') && !t.id.startsWith('sectional-') && !t.id.startsWith('orig-')).flatMap(t => t.questions))

let seed = 20261105
const rand = () => {
  seed = (seed + 0x6D2B79F5) | 0
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed)
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296
}
const shuffle = (a) => { a = [...a]; for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rand() * (i + 1)); [a[i], a[j]] = [a[j], a[i]] } return a }

// Questions carry their book chapters as tags (scripts/tag-chapters.mjs)
const inChapter = (subject, chapter) =>
  (q) => (q.tags || []).some(tag => tag.subject === subject && tag.topic === chapter.name)

const slug = (s) => s.toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
const used = new Set()
const papers = []

for (let round = 1; round <= ROUNDS; round++) {
  for (const [subject, chapters] of Object.entries(SYLLABUS_CHAPTERS)) {
    const pools = chapters.map(ch => shuffle(usable.filter(q => !taken.has(q.id) && inChapter(subject, ch)(q))))
    const live = chapters.map((ch, i) => pools[i].length > 0)
    // Chapters with no past-paper questions (e.g. Optimal BST) share their slots out
    const liveChapters = chapters.filter((_, i) => live[i])
    const liveQuotas = chapterQuotas(liveChapters, PER_PAPER)
    const quota = chapters.map((_, i) => (live[i] ? liveQuotas[liveChapters.indexOf(chapters[i])] : 0))

    const picked = []
    const counts = chapters.map(() => 0)
    let oneLeft = ONE_MARK
    let twoLeft = PER_PAPER - ONE_MARK
    const take = (i) => {
      const avail = pools[i].filter(q => !used.has(q.id))
      if (!avail.length) return false
      const want = oneLeft >= twoLeft ? 1 : 2
      const q = avail.find(x => x.marks === want) || avail[0]
      used.add(q.id)
      picked.push({ q, chapter: i })
      counts[i]++
      if (q.marks === 1) oneLeft--; else twoLeft--
      return true
    }
    let short = 0
    chapters.forEach((_, i) => { for (let k = 0; k < quota[i]; k++) if (!take(i)) short++ })
    // Fill any shortfall from the largest chapters that still have questions
    const bySize = chapters.map((c, i) => i).sort((a, b) => chapters[b].pages - chapters[a].pages)
    while (short > 0) {
      const i = bySize.find(k => pools[k].some(q => !used.has(q.id)))
      if (i === undefined) throw new Error(`${subject}: not enough past-paper questions`)
      take(i)
      short--
    }

    papers.push({
      id: `pyq-sectional-${slug(subject)}-${round}`,
      title: `${subject} PYQ Sectional Mock ${round}`,
      subject,
      durationMinutes: 45,
      totalQuestions: picked.length,
      difficulty: 'Medium',
      chapters: chapters.map((c, i) => ({ name: c.name, count: counts[i] })).filter(c => c.count > 0),
      // In chapter order, one-mark before two-mark within a chapter
      questions: picked.sort((a, b) => a.chapter - b.chapter || a.q.marks - b.q.marks).map(p => p.q.id)
    })
  }
}

const file = 'shared/mockTests.js'
let src = fs.readFileSync(file, 'utf8').split('\r\n').join('\n')
const START = '  // PYQ-SECTIONALS-START: generated by scripts/generate-pyq-sectionals.mjs'
const END = '  // PYQ-SECTIONALS-END'
const block = `${START}\n${papers.map(p => `  ${JSON.stringify(p)},`).join('\n')}\n${END}`
if (src.includes(START)) src = src.replace(new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}`), block)
else throw new Error('Add the PYQ-SECTIONALS markers to shared/mockTests.js first')
fs.writeFileSync(file, src)

for (const p of papers.slice(0, papers.length / ROUNDS)) {
  console.log(`${p.subject.padEnd(38)} ${p.chapters.map(c => `${c.name.split(' (')[0]} ${c.count}`).join(' | ')}`)
}
const marks = papers.map(p => p.questions.reduce((s, id) => s + questions.find(q => q.id === id).marks, 0))
console.log(`${papers.length} papers, ${new Set(papers.flatMap(p => p.questions)).size} unique questions, marks per paper: ${Math.min(...marks)}-${Math.max(...marks)}`)
